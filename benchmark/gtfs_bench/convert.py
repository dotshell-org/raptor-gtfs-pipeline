"""Convert the merged tiers with the pipeline, measuring how long and how much memory.

    python -m gtfs_bench.convert                                  # every merged tier
    python -m gtfs_bench.convert --tiers metropole:lyon,france --xmx 12g

Each tier's zip goes through the pipeline's own CLI, as for any network, with a one-period
profile: the reference day (results/reference_day.json), `onDate`. The output is
data/raptor/<tier>/bench/{stops,routes,index}.bin plus the pipeline's dataset.json.

While the JVM runs, its peak working set is read from the OS (Windows records the peak
itself, so nothing is lost between two samples), which includes the heap and everything
around it. The numbers land in results/pipeline.csv. The pipeline is not modified for the
benchmark: it runs from `./gradlew :cli:installDist`.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import json
import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import asdict, dataclass, field, fields
from pathlib import Path

import psutil

from .catalog import BENCHMARK_DIR

REPO_DIR = BENCHMARK_DIR.parent
INSTALL_DIR = REPO_DIR / "cli" / "build" / "install" / "raptor-gtfs-pipeline"
MAIN_CLASS = "eu.dotshell.raptor.gtfs.pipeline.cli.MainKt"
DATA_DIR = BENCHMARK_DIR / "data"
MERGED_DIR = DATA_DIR / "merged"
RAPTOR_DIR = DATA_DIR / "raptor"
RESULTS_DIR = BENCHMARK_DIR / "results"
PERIOD = "bench"
TIER_ORDER = ("metropole", "region", "france")


@dataclass
class ConversionResult:
    tier: str
    status: str = "failed"          # ok | failed | timeout | out_of_memory
    exit_code: int | None = None
    seconds: float = 0.0
    peak_memory_mb: float = 0.0
    xmx: str = ""
    java: str = ""
    input_zip_mb: float = 0.0
    stops_bin_mb: float = 0.0
    routes_bin_mb: float = 0.0
    index_bin_mb: float = 0.0
    stops: int | None = None
    routes: int | None = None
    trips: int | None = None
    stop_times: int | None = None
    transfers: int | None = None
    #: Trips of the period the pipeline found, before RouteBuilder keeps one stop sequence
    #: per route and direction and TripBuilder drops the trips that do not cover it.
    trips_found: int | None = None
    trips_kept_share: float | None = None
    error: str = ""
    log: str = ""
    extra: dict = field(default_factory=dict)


CSV_COLUMNS = [f.name for f in fields(ConversionResult) if f.name not in ("log", "extra")]


def write_profile(day: dt.date, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by gtfs_bench.convert: one period, the benchmark's reference day.\n"
        "network: france-benchmark\n"
        "periods:\n"
        f"  {PERIOD}:\n"
        f"    description: Benchmark reference day {day.isoformat()}\n"
        "    rules:\n"
        f"      - onDate: \"{day.isoformat()}\"\n"
        "# Services that do not run that day are left out.\n"
        "unmatched: drop\n",
        encoding="utf-8")
    return path


def java_executable(java: str | None = None) -> str:
    if java:
        return java
    home = os.environ.get("JAVA_HOME")
    if home and (Path(home) / "bin" / "java.exe").exists():
        return str(Path(home) / "bin" / "java.exe")
    return shutil.which("java") or "java"


def java_version(java: str) -> str:
    out = subprocess.run([java, "-version"], capture_output=True, text=True)
    first = (out.stderr or out.stdout).splitlines()
    return first[0].strip() if first else "?"


def _peak(process: psutil.Process) -> float:
    """Peak working set of the JVM so far, in bytes (current RSS off Windows); 0 once it is gone.

    java is started directly, not through the launcher script, so there is no child to add.
    """
    try:
        info = process.memory_info()
        return float(getattr(info, "peak_wset", info.rss))
    except psutil.Error:  # it exited between two samples
        return 0.0


def convert_tier(zip_path: Path, out_dir: Path, profile: Path, xmx: str = "12g", java: str | None = None,
                 timeout_s: int = 3 * 3600, extra_jvm_args: tuple[str, ...] = ()) -> ConversionResult:
    """Run the pipeline on one merged zip and measure it."""
    if not (INSTALL_DIR / "lib").exists():
        raise FileNotFoundError(f"{INSTALL_DIR} is missing: run ./gradlew :cli:installDist")
    java = java_executable(java)
    result = ConversionResult(tier=zip_path.stem, xmx=xmx, java=java_version(java),
                              input_zip_mb=round(zip_path.stat().st_size / 1024**2, 1))
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    log_path = out_dir / "convert.log"
    command = [java, f"-Xmx{xmx}", *extra_jvm_args, "-cp", str(INSTALL_DIR / "lib" / "*"), MAIN_CLASS,
               "convert", "--input", str(zip_path), "--output", str(out_dir), "--profile", str(profile)]
    started = time.perf_counter()
    peak = 0.0
    with log_path.open("w", encoding="utf-8", errors="replace") as log:
        process = psutil.Popen(command, stdout=log, stderr=subprocess.STDOUT)
        try:
            while process.poll() is None:
                peak = max(peak, _peak(process))
                if time.perf_counter() - started > timeout_s:
                    process.kill()
                    result.status = "timeout"
                    break
                time.sleep(0.25)
        finally:
            if process.poll() is None:
                process.kill()
    result.seconds = round(time.perf_counter() - started, 1)
    result.peak_memory_mb = round(peak / 1024**2)
    result.exit_code = process.returncode
    text = log_path.read_text(encoding="utf-8", errors="replace")
    result.log = str(log_path)

    if "OutOfMemoryError" in text:
        result.status = "out_of_memory"
    elif result.status != "timeout":
        result.status = "ok" if result.exit_code == 0 and (out_dir / "dataset.json").exists() else "failed"
    if result.status != "ok":
        lines = [l for l in text.splitlines() if l.strip()]
        cause = next((l for l in lines if "Exception" in l or "Error" in l), lines[-1] if lines else "")
        result.error = cause.strip()[:300]
        return result

    dataset = json.loads((out_dir / "dataset.json").read_text(encoding="utf-8"))
    period = next(p for p in dataset["periods"] if p["name"] == PERIOD)
    stats = period.get("stats", {})
    for key in ("stops", "routes", "trips", "stop_times", "transfers"):
        setattr(result, key, stats.get(key))
    found = re.search(rf"Found (\d+) trips for period {PERIOD}", text)
    if found:
        result.trips_found = int(found.group(1))
        if result.trips_found and result.trips is not None:
            result.trips_kept_share = round(result.trips / result.trips_found, 4)
    for name, attr in (("stops.bin", "stops_bin_mb"), ("routes.bin", "routes_bin_mb"), ("index.bin", "index_bin_mb")):
        path = out_dir / PERIOD / name
        if path.exists():
            setattr(result, attr, round(path.stat().st_size / 1024**2, 2))
    result.extra = {k: v for k, v in stats.items() if k not in ("stops", "routes", "trips", "stop_times", "transfers")}
    return result


def merged_tiers(merged_dir: Path = MERGED_DIR) -> list[tuple[str, Path]]:
    """(tier key, zip) for every merged tier, smallest kinds first."""
    found = []
    for kind in TIER_ORDER:
        for path in sorted((merged_dir / kind).glob("*.zip")):
            key = "france" if kind == "france" else f"{kind}:{path.stem.split('-', 1)[1]}"
            found.append((key, path))
    return found


def write_results(results: list[ConversionResult], path: Path = RESULTS_DIR / "pipeline.csv") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for result in results:
            writer.writerow(asdict(result))
    return path


def convert_all(day: dt.date, tiers: list[str] | None = None, xmx: str = "12g", java: str | None = None,
                timeout_s: int = 3 * 3600, progress=print) -> list[ConversionResult]:
    profile = write_profile(day, DATA_DIR / "profiles" / "bench.yaml")
    results = []
    for key, zip_path in merged_tiers():
        if tiers and key not in tiers:
            continue
        result = convert_tier(zip_path, RAPTOR_DIR / zip_path.stem, profile, xmx, java, timeout_s)
        result.tier = key
        results.append(result)
        write_results(results)  # as it goes: a long run that breaks keeps what it measured
        progress(f"{key}: {result.status} in {result.seconds} s, peak {result.peak_memory_mb} MB"
                 + (f", {result.trips} trips, {result.stops} stops, routes.bin {result.routes_bin_mb} MB" if result.status == "ok"
                    else f" — {result.error}"))
    return results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m gtfs_bench.convert", description=__doc__.splitlines()[0])
    parser.add_argument("--date", help="reference day, YYYY-MM-DD (default: results/reference_day.json)")
    parser.add_argument("--tiers", help="comma-separated tier keys (default: every merged tier)")
    parser.add_argument("--xmx", default="12g", help="JVM heap ceiling (default 12g; this machine has 15 GB)")
    parser.add_argument("--java", help="java executable (default: $JAVA_HOME, then PATH)")
    parser.add_argument("--timeout", type=int, default=3 * 3600, help="seconds per tier")
    args = parser.parse_args(argv)

    day = dt.date.fromisoformat(args.date) if args.date else dt.date.fromisoformat(
        json.loads((RESULTS_DIR / "reference_day.json").read_text(encoding="utf-8"))["reference_date"])
    results = convert_all(day, args.tiers.split(",") if args.tiers else None, args.xmx, args.java, args.timeout)
    path = write_results(results)
    print(f"{sum(r.status == 'ok' for r in results)}/{len(results)} converted -> {path}")
    return 0 if all(r.status == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
